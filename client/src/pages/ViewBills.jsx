import React, { useState, useEffect } from "react";
import PageLayout from "../components/PageLayout.jsx";
import PrimaryButton from "../components/PrimaryButton.jsx";
import LoadingScreen from "../components/LoadingScreen.jsx";
import EmptyState from "../components/EmptyState.jsx";
import { getMyBills } from "../api/billAPI.js";
import { useNavigate } from "react-router-dom";

const STATUS_STYLES = {
  paid:           "bg-green-100 text-green-700",
  partially_paid: "bg-blue-100 text-blue-700",
  unpaid:         "bg-yellow-100 text-yellow-800",
  overdue:        "bg-red-100 text-red-700",
  waived:         "bg-neutral-100 text-neutral-600",
};

const MEAL_EMOJI = { breakfast: "🌅", lunch: "☀️", dinner: "🌙" };

export default function ViewBills() {
  const [loading, setLoading] = useState(true);
  const [bills, setBills] = useState([]);
  const [expandedId, setExpandedId] = useState(null);
  const navigate = useNavigate();

  useEffect(() => {
    const fetchBills = async () => {
      try {
        setLoading(true);
        const res = await getMyBills({ limit: 50 });
        if (res.data?.success) setBills(res.data.data || []);
      } catch (err) {
        console.error("Error fetching bills:", err);
        alert(err.response?.data?.message || "Failed to load bills");
      } finally {
        setLoading(false);
      }
    };
    fetchBills();
  }, []);

  if (loading) return <LoadingScreen message="Loading bills..." />;

  const pendingExists = bills.some((b) =>
    ["unpaid", "partially_paid", "overdue"].includes(b.paymentStatus)
  );

  return (
    <PageLayout title="Bills & Payments" subtitle="Your monthly mess bills and payment status.">
      {bills.length === 0 ? (
        <EmptyState title="No bills found" subtitle="Bills will appear here once generated by the admin." />
      ) : (
        <section className="space-y-4">
          {bills.map((bill) => {
            const isExpanded = expandedId === bill._id;
            return (
              <div
                key={bill._id}
                className="bg-white border border-neutral-200 shadow-sm rounded-xl overflow-hidden"
              >
                {/* Bill header row */}
                <div
                  className="p-5 flex justify-between items-center cursor-pointer hover:bg-neutral-50 transition"
                  onClick={() => setExpandedId(isExpanded ? null : bill._id)}
                >
                  <div>
                    <h2 className="text-base font-semibold text-neutral-800">
                      {new Date(bill.year, bill.month - 1).toLocaleString("default", {
                        month: "long",
                        year: "numeric",
                      })}
                    </h2>
                    <div className="flex gap-4 mt-1 text-sm text-neutral-600">
                      <span>Total: <strong>₹{(bill.totalAmount ?? 0).toFixed(2)}</strong></span>
                      {bill.amountDue > 0 && (
                        <span>Due: <strong className="text-red-600">₹{(bill.amountDue ?? 0).toFixed(2)}</strong></span>
                      )}
                    </div>
                  </div>

                  <div className="flex items-center gap-3">
                    <span className={`px-3 py-1 rounded-full text-sm font-medium ${STATUS_STYLES[bill.paymentStatus] || ""}`}>
                      {bill.paymentStatus?.replace("_", " ").replace(/\b\w/g, (c) => c.toUpperCase())}
                    </span>
                    <span className="text-neutral-400 text-lg">{isExpanded ? "▲" : "▼"}</span>
                  </div>
                </div>

                {/* Expanded meal breakdown */}
                {isExpanded && (
                  <div className="border-t border-neutral-100 px-5 py-4 bg-neutral-50">
                    {bill.mealWiseCharges?.length > 0 ? (
                      <>
                        <p className="text-xs font-medium text-neutral-500 uppercase tracking-wide mb-3">
                          Meal-wise Charges
                        </p>
                        <div className="space-y-2">
                          {bill.mealWiseCharges.map((m) => (
                            <div key={m.mealType} className="flex justify-between text-sm">
                              <span className="text-neutral-700">
                                {MEAL_EMOJI[m.mealType] || "🍽️"}{" "}
                                <span className="capitalize">{m.mealType}</span>
                                <span className="text-neutral-400 ml-1">
                                  ({m.daysConsumed} × ₹{m.rate})
                                </span>
                              </span>
                              <span className="font-medium">₹{m.totalAmount.toFixed(2)}</span>
                            </div>
                          ))}
                        </div>
                        <div className="border-t border-neutral-200 mt-3 pt-3 flex justify-between text-sm font-semibold">
                          <span>Total Bill</span>
                          <span>₹{(bill.totalAmount ?? 0).toFixed(2)}</span>
                        </div>
                        {bill.amountPaid > 0 && (
                          <div className="flex justify-between text-sm text-green-700 mt-1">
                            <span>Amount Paid</span>
                            <span>₹{(bill.amountPaid ?? 0).toFixed(2)}</span>
                          </div>
                        )}
                        {bill.amountDue > 0 && (
                          <div className="flex justify-between text-sm text-red-600 mt-1 font-semibold">
                            <span>Amount Due</span>
                            <span>₹{(bill.amountDue ?? 0).toFixed(2)}</span>
                          </div>
                        )}
                      </>
                    ) : (
                      <p className="text-sm text-neutral-400">No meal breakdown available.</p>
                    )}
                  </div>
                )}
              </div>
            );
          })}
        </section>
      )}

      {pendingExists && (
        <div className="mt-8 flex justify-end">
          <PrimaryButton onClick={() => navigate("/pay-pending")}>
            Pay Pending Bills
          </PrimaryButton>
        </div>
      )}
    </PageLayout>
  );
}
